"""Translate the energy/first-derivative scalar expressions without reordering.

Run after changing pbe_lda_calc or pbe_lsd_calc:
python3 tests/pw_gpu_integrated/generate_pbe_kernel.py
The independent numerical reference remains the compiled Fortran routine.
"""
import ast
import argparse
from pathlib import Path
import re
import textwrap

ROOT = Path(__file__).resolve().parents[2]


def first_derivative_source(routine, last_output):
    source = (ROOT / "src/xc/xc_pbe.F").read_text()
    source = source.split(f"   SUBROUTINE {routine}(", 1)[1]
    source = "gamma_var =" + source.split("      gamma_var =", 1)[1]
    last = re.search(r"\n\s*" + last_output + r"\(ii\) =.*?\n\s*END IF", source, re.S)
    assert last, (routine, last_output)
    source = source[:last.end()]
    source = re.sub(r"&\s*\n\s*", "", source).lower()
    return re.sub(r"_dp\b", "", source)


DERIVATIVE_CONDITIONS = {
    "if (grad_deriv >= 0) then": "grad_deriv >= 0",
    "if (grad_deriv >= 1 .or. grad_deriv == -1) then": "grad_deriv >= 1 || grad_deriv == -1",
}


def generate_lda():
    source = first_derivative_source("pbe_lda_calc", "e_ndrho")
    names = {"rho": "rho", "norm_drho": "norm_drho", "e_0": "e0",
             "e_rho": "erho", "e_ndrho": "enorm"}

    def expr(node):
        if isinstance(node, ast.Name):
            return node.id
        if isinstance(node, ast.Constant):
            return str(float(node.value))
        if isinstance(node, ast.UnaryOp):
            return "(-" + expr(node.operand) + ")"
        if isinstance(node, ast.Call):
            name = node.func.id
            if name in names:
                return names[name] + "[i]"
            return name + "(" + ", ".join(expr(a) for a in node.args) + ")"
        if isinstance(node, ast.BinOp):
            a, b = expr(node.left), expr(node.right)
            if isinstance(node.op, ast.Mult):
                return f"PW_GPU_DMUL({a}, {b})"
            if isinstance(node.op, ast.Add):
                return f"PW_GPU_DADD({a}, {b})"
            if isinstance(node.op, ast.Sub):
                return f"PW_GPU_DADD({a}, -({b}))"
            if isinstance(node.op, ast.Div):
                return f"({a} / {b})"
            if isinstance(node.op, ast.Pow):
                if isinstance(node.right, ast.Constant) and node.right.value == 2:
                    return f"PW_GPU_DMUL({a}, {a})"
                return f"pow({a}, {b})"
        raise ValueError(ast.dump(node))

    out = ["/* SPDX-License-Identifier: GPL-2.0-or-later */",
           "/* Generated by tests/pw_gpu_integrated/generate_pbe_kernel.py.",
           " * CP2K pbe_lda_calc/pbe_lsd_calc: identical scalar expression trees.",
           " * Energy and first derivatives; higher orders stay on CPU. */",
           "#ifndef PW_GPU_PBE_H", "#define PW_GPU_PBE_H",
           '#include "pw_gpu_grid_ops.h"', "",
           "PW_GPU_ELEMENTAL void pw_pbe_lda_elem(",
           "    const double *rho, const double *norm_drho, double *e0,",
           "    double *erho, double *enorm, size_t i, int grad_deriv,",
           "    double epsilon_rho, double kappa, double beta, double mu,",
           "    double scale_ec, double scale_ex) {",
           "  PW_GPU_NO_CONTRACT",
           "  if (!(rho[i] > epsilon_rho)) return;",
           "  const double pi = 3.141592653589793238462643383279502884;"]
    seen = set()
    depth = 1
    for line in source.splitlines():
        line = line.strip()
        if not line or line.startswith(("!", "do ", "select case ", "case ")):
            continue
        if line == "if (my_rho > epsilon_rho) then":
            continue
        if line.startswith("if "):
            out.append("  " * depth + f"if ({DERIVATIVE_CONDITIONS[line]}) {{")
            depth += 1
            continue
        if line == "end if":
            depth -= 1
            out.append("  " * depth + "}")
            continue
        lhs, rhs = line.split("=", 1)
        lhs = lhs.strip()
        decl = ""
        if "(" not in lhs and lhs not in seen:
            decl = "const double "
            seen.add(lhs)
        out.append("  " * depth + decl + expr(ast.parse(lhs, mode="eval").body) + " = " +
                   expr(ast.parse(rhs.strip(), mode="eval").body) + ";")
    assert depth == 1
    out += ["}", ""]
    # Initialization also contains temporaries used only by higher derivatives.
    while True:
        text = "\n".join(out)
        unused = [line for line in out if (m := re.match(r"\s*const double (\w+) =", line))
                  and len(re.findall(r"\b" + m[1] + r"\b", text)) == 1]
        if not unused:
            return "\n".join(
                textwrap.fill(line, width=100, subsequent_indent="        ",
                              break_long_words=False, break_on_hyphens=False,
                              replace_whitespace=False) if len(line) > 100 else line
                for line in out)
        out = [line for line in out if line not in unused]


def generate_lsd():
    source = first_derivative_source("pbe_lsd_calc", "e_ndrb")
    outputs = {"e_0", "e_ra", "e_rb", "e_ndr", "e_ndra", "e_ndrb"}
    inputs = {"rhoa": "rhoa", "rhob": "rhob", "norm_drho": "ndr",
              "norm_drhoa": "ndra", "norm_drhob": "ndrb"}

    def expr(node):
        if isinstance(node, ast.Name):
            return node.id
        if isinstance(node, ast.Constant):
            return str(float(node.value))
        if isinstance(node, ast.UnaryOp):
            return "(-" + expr(node.operand) + ")"
        if isinstance(node, ast.Call):
            name = node.func.id
            if name in outputs:
                return "*" + name
            if name in inputs:
                return inputs[name]
            if name == "epsilon":
                return "2.2204460492503131e-16"
            return ("fmax" if name == "max" else name) + "(" + ", ".join(
                expr(arg) for arg in node.args) + ")"
        if isinstance(node, ast.BinOp):
            left, right = expr(node.left), expr(node.right)
            if isinstance(node.op, ast.Mult):
                return f"PW_GPU_DMUL({left}, {right})"
            if isinstance(node.op, ast.Add):
                return f"PW_GPU_DADD({left}, {right})"
            if isinstance(node.op, ast.Sub):
                return f"PW_GPU_DADD({left}, -({right}))"
            if isinstance(node.op, ast.Div):
                return f"({left} / {right})"
            if isinstance(node.op, ast.Pow):
                if isinstance(node.right, ast.Constant) and node.right.value == 2:
                    return f"PW_GPU_DMUL({left}, {left})"
                return f"pow({left}, {right})"
        raise ValueError(ast.dump(node))

    out = [
        "#ifndef PW_GPU_PBE_FUNC",
        "#define PW_GPU_PBE_FUNC PW_GPU_ELEMENTAL",
        "#endif",
        "PW_GPU_PBE_FUNC void pw_pbe_lsd_elem(",
        "    double rhoa, double rhob, double ndr, double ndra, double ndrb,",
        "    double epsilon_rho, double scale_ex, double scale_ec, int grad_deriv,",
        "    double *e_0, double *e_ra, double *e_rb,",
        "    double *e_ndr, double *e_ndra, double *e_ndrb) {",
        "  PW_GPU_NO_CONTRACT",
        "  const double pi = 3.141592653589793238462643383279502884;",
        "  const double kappa = 0.804, beta = 0.066725;",
        "  const double mu = PW_GPU_DMUL(beta, PW_GPU_DMUL(pi, pi)) / 3.0;",
    ]
    seen = set()
    depth = 1
    for line in source.splitlines():
        line = line.strip()
        if not line or line.startswith(("!", "do ", "select case ", "case ")):
            continue
        if line == "if (my_rho > epsilon_rho) then":
            out.append("  if (!(my_rho > epsilon_rho)) return;")
            continue
        if line.startswith("if "):
            out.append("  " * depth + f"if ({DERIVATIVE_CONDITIONS[line]}) {{")
            depth += 1
            continue
        if line == "end if":
            depth -= 1
            out.append("  " * depth + "}")
            continue
        lhs, rhs = (part.strip() for part in line.split("=", 1))
        decl = ""
        if "(" not in lhs and lhs not in seen:
            decl = "double " if lhs in {"my_rhoa", "my_rhob", "my_rho"} else "const double "
            seen.add(lhs)
        out.append("  " * depth + decl + expr(ast.parse(lhs, mode="eval").body) +
                   " = " + expr(ast.parse(rhs, mode="eval").body) + ";")
    assert depth == 1
    out += ["}", "#endif", ""]
    return "\n".join(textwrap.fill(line, width=100, subsequent_indent="        ",
                                  break_long_words=False, break_on_hyphens=False,
                                  replace_whitespace=False) if len(line) > 100 else line
                     for line in out)


def generate():
    return generate_lda() + "\n" + generate_lsd()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "src/pw/gpu/pw_gpu_pbe.h"
    generated = generate()
    if args.check:
        if target.read_text() != generated:
            raise SystemExit("pw_gpu_pbe.h is stale; regenerate it")
        print("PASS generated LDA/LSD PBE kernels")
    else:
        target.write_text(generated)
