"""Translate the energy/first-derivative scalar expressions without reordering.

Run after changing pbe_lda_calc: python3 tests/pw_gpu_integrated/generate_pbe_kernel.py
The independent numerical reference remains the compiled Fortran routine.
"""
import ast
from pathlib import Path
import re
import textwrap

ROOT = Path(__file__).resolve().parents[2]


def generate():
    source = (ROOT / "src/xc/xc_pbe.F").read_text()
    source = source.split("   SUBROUTINE pbe_lda_calc(", 1)[1]
    source = source.split("      gamma_var =", 1)[1]
    source = "gamma_var =" + source.split("               IF (grad_deriv > 1) THEN", 1)[0]
    source = re.sub(r"&\s*\n\s*", "", source).lower()
    source = re.sub(r"_dp\b", "", source)
    names = {"rho": "rho", "norm_drho": "norm_drho", "e_0": "e0",
             "e_rho": "erho", "e_ndrho": "enorm"}

    def expr(node):
        if isinstance(node, ast.Name):
            return node.id
        if isinstance(node, ast.Constant):
            return str(float(node.value))
        if isinstance(node, ast.UnaryOp):
            return "(-" + expr(node.operand) + ")"
        if isinstance(node, ast.Call):
            name = node.func.id
            if name in names:
                return names[name] + "[i]"
            return name + "(" + ", ".join(expr(a) for a in node.args) + ")"
        if isinstance(node, ast.BinOp):
            a, b = expr(node.left), expr(node.right)
            if isinstance(node.op, ast.Mult):
                return f"PW_GPU_DMUL({a}, {b})"
            if isinstance(node.op, ast.Add):
                return f"PW_GPU_DADD({a}, {b})"
            if isinstance(node.op, ast.Sub):
                return f"PW_GPU_DADD({a}, -({b}))"
            if isinstance(node.op, ast.Div):
                return f"({a} / {b})"
            if isinstance(node.op, ast.Pow):
                if isinstance(node.right, ast.Constant) and node.right.value == 2:
                    return f"PW_GPU_DMUL({a}, {a})"
                return f"pow({a}, {b})"
        raise ValueError(ast.dump(node))

    out = ["/* SPDX-License-Identifier: GPL-2.0-or-later */",
           "/* Generated by tests/pw_gpu_integrated/generate_pbe_kernel.py.",
           " * CP2K pbe_lda_calc: identical scalar expression trees, rounded adds",
           " * and multiplies. grad_deriv is 0 or 1; higher orders stay on CPU. */",
           "#ifndef PW_GPU_PBE_H", "#define PW_GPU_PBE_H",
           '#include "pw_gpu_grid_ops.h"', "",
           "PW_GPU_ELEMENTAL void pw_pbe_lda_elem(",
           "    const double *rho, const double *norm_drho, double *e0,",
           "    double *erho, double *enorm, size_t i, int grad_deriv,",
           "    double epsilon_rho, double kappa, double beta, double mu,",
           "    double scale_ec, double scale_ex) {",
           "  PW_GPU_NO_CONTRACT",
           "  if (!(rho[i] > epsilon_rho)) return;",
           "  const double pi = 3.141592653589793238462643383279502884;"]
    seen = set()
    for line in source.splitlines():
        line = line.strip()
        if not line or line.startswith("!") or line.startswith("do "):
            continue
        if line == "if (my_rho > epsilon_rho) then":
            continue
        if line == "if (grad_deriv /= 0) then":
            out.append("  if (grad_deriv != 0) {")
            continue
        lhs, rhs = line.split("=", 1)
        lhs = lhs.strip()
        decl = ""
        if "(" not in lhs and lhs not in seen:
            decl = "const double "
            seen.add(lhs)
        out.append("    " + decl + expr(ast.parse(lhs, mode="eval").body) + " = " +
                   expr(ast.parse(rhs.strip(), mode="eval").body) + ";")
    out += ["  }", "}", "#endif", ""]
    # Initialization also contains temporaries used only by higher derivatives.
    while True:
        text = "\n".join(out)
        unused = [line for line in out if (m := re.match(r"\s*const double (\w+) =", line))
                  and len(re.findall(r"\b" + m[1] + r"\b", text)) == 1]
        if not unused:
            return "\n".join(
                textwrap.fill(line, width=100, subsequent_indent="        ",
                              break_long_words=False, break_on_hyphens=False,
                              replace_whitespace=False) if len(line) > 100 else line
                for line in out)
        out = [line for line in out if line not in unused]


if __name__ == "__main__":
    (ROOT / "src/pw/gpu/pw_gpu_pbe.h").write_text(generate())
